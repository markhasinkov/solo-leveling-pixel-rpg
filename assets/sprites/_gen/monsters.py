def knight_ant():
    car, card, carl = hx('#7a421e'), hx('#3f1f0c'), hx('#b06a34')
    chitin, eye, eye_l = hx('#241006'), hx('#ffd23c'), hx('#fff0a0')
    steel, steel_l = hx('#aab6c2'), hx('#eef6fc')
    r = png.blank(64, 64)
    box = lambda x0, y0, x1, y1, c: rect(r, x0, y0, x1, y1, c)

    # лапы (задние)
    for (x0, y0, x1, y1) in ((18, 34, 8, 42), (18, 42, 7, 50), (46, 34, 56, 42), (46, 42, 57, 50)):
        line(r, x0, y0, x1, y1, card)
        line(r, x0, y0 - 1, x1, y1 - 1, car)
        put(r, x1, y1, chitin)
    # брюшко
    ellipse(r, 32, 48, 12, 8, card)
    ellipse(r, 32, 47, 10, 6, car)
    for y in (44, 48, 52):
        line(r, 24, y, 40, y, card)
    put(r, 27, 45, carl); put(r, 37, 47, carl)

    # ноги
    for (x, y) in ((23, 56), (30, 57), (37, 57), (42, 56)):
        line(r, x, 54, x - 4, 62, card)
        line(r, x + 1, 54, x + 3, 62, card)
        put(r, x - 4, 63, chitin); put(r, x + 3, 63, chitin)

    # грудь
    ellipse(r, 32, 32, 13, 11, car)
    ellipse(r, 32, 31, 11, 9, card)
    poly(r, [(21, 27), (43, 27), (44, 38), (32, 43), (20, 38)], carl)
    poly(r, [(22, 28), (32, 28), (31, 41), (21, 37)], car)
    box(30, 28, 34, 41, card)
    for y in (31, 35, 39):
        line(r, 22, y, 42, y, card)
        put(r, 25, y + 1, carl); put(r, 39, y + 1, carl)
    # шипы
    for (x, y) in ((18, 28), (46, 28), (20, 35), (44, 35)):
        line(r, x, y, x + (-3 if x < 32 else 3), y - 3, carl)

    # передние лапы с копьём
    line(r, 20, 30, 12, 38, car); line(r, 20, 31, 12, 39, card)
    line(r, 44, 30, 52, 38, car); line(r, 44, 31, 52, 39, card)

    # голова
    ellipse(r, 32, 17, 12, 9, car)
    ellipse(r, 32, 17, 10, 7, carl)
    poly(r, [(21, 13), (25, 8), (39, 8), (43, 13), (42, 21), (32, 25), (22, 21)], car)
    # глаза-фасетки
    poly(r, [(23, 14), (29, 12), (30, 18), (24, 19)], eye)
    poly(r, [(41, 14), (35, 12), (34, 18), (40, 19)], eye)
    for (x, y) in ((25, 14), (27, 15), (36, 15), (38, 14)):
        put(r, x, y, hx('#2a1a08'))
    put(r, 26, 13, eye_l); put(r, 37, 13, eye_l)
    # жвалы
    poly(r, [(22, 22), (28, 22), (29, 27), (24, 29), (21, 26)], chitin)
    poly(r, [(42, 22), (36, 22), (35, 27), (40, 29), (43, 26)], chitin)
    line(r, 23, 25, 26, 27, card)
    line(r, 41, 25, 38, 27, card)
    # усики
    line(r, 27, 9, 20, 1, card); line(r, 37, 9, 44, 1, card)
    put(r, 19, 0, carl); put(r, 44, 0, carl)
    line(r, 29, 8, 28, 4, carl); line(r, 35, 8, 36, 4, carl)

    # копьё
    box(53, 6, 55, 59, hx('#5b3f22'))
    line(r, 54, 7, 54, 58, hx('#7a5a30'))
    poly(r, [(50, 2), (54, 0), (58, 2), (56, 10), (52, 10)], steel)
    poly(r, [(52, 3), (54, 1), (56, 3), (55, 8), (53, 8)], steel_l)
    line(r, 50, 10, 58, 10, hx('#c8a040'))
    # блики
    for (x, y) in ((25, 30), (38, 33), (23, 45), (41, 50)):
        put(r, x, y, carl)
    return r


def ice_bear():
    f, fd, fl = hx('#cfeaf8'), hx('#8ab4cc'), hx('#f4fcff')
    fdd = hx('#5a86a8')
    ice, ice_d = hx('#8fd8f0'), hx('#3d6f96')
    eye, claw = hx('#2a6a9a'), hx('#e8f4ff')
    r = png.blank(64, 64)
    box = lambda x0, y0, x1, y1, c: rect(r, x0, y0, x1, y1, c)

    # хвост
    poly(r, [(12, 30), (4, 33), (3, 39), (11, 39)], f)
    line(r, 6, 35, 10, 37, fd)

    # задние лапы (короткие и толстые)
    box(11, 45, 21, 56, f)
    box(11, 45, 12, 55, fl)
    box(20, 45, 21, 55, fd)
    box(9, 55, 23, 63, fd)
    box(9, 55, 23, 56, fl)
    box(9, 62, 23, 63, fdd)

    # тело и плечевой горб
    ellipse(r, 27, 36, 20, 15, f)
    ellipse(r, 26, 34, 17, 12, fl)
    ellipse(r, 37, 31, 13, 11, f)
    ellipse(r, 35, 29, 10, 8, fl)
    poly(r, [(12, 40), (46, 40), (44, 51), (14, 51)], f)
    line(r, 13, 47, 43, 47, fd)
    line(r, 16, 42, 42, 42, fd)

    # ледяные шипы на спине
    for (x, y, h, w) in ((16, 22, 7, 2), (22, 18, 9, 2), (29, 16, 10, 3), (36, 18, 8, 2)):
        poly(r, [(x - w, y), (x, y - h), (x + w, y)], ice)
        line(r, x, y - h + 1, x, y, ice_d)
        put(r, x, y - h, hx('#ffffff'))
        put(r, x - w + 1, y - 1, hx('#c8f4ff'))

    # голова: короткая шея, круглая морда
    ellipse(r, 46, 28, 12, 11, f)
    ellipse(r, 45, 27, 10, 9, fl)
    # уши
    ellipse(r, 40, 20, 3, 3, f)
    ellipse(r, 52, 19, 3, 3, f)
    ellipse(r, 40, 20, 2, 2, fdd)
    ellipse(r, 52, 19, 2, 2, fdd)
    # морда, короче и круглее
    poly(r, [(51, 25), (59, 26), (62, 30), (58, 36), (50, 34)], fl)
    box(58, 28, 62, 32, ice_d)
    put(r, 61, 28, hx('#1a2a36')); put(r, 61, 31, hx('#1a2a36'))
    line(r, 54, 35, 59, 34, fdd)
    put(r, 56, 36, hx('#ffffff')); put(r, 58, 36, hx('#ffffff'))
    # мех на щеках
    for (x, y) in ((49, 30), (49, 33), (52, 36), (46, 35)):
        put(r, x, y, fd)
        put(r, x, y + 1, fl)
    # глаза
    poly(r, [(41, 24), (46, 23), (47, 26), (42, 27)], eye)
    put(r, 44, 24, hx('#d8f6ff'))
    line(r, 41, 22, 46, 21, fdd)
    put(r, 39, 27, fd); put(r, 50, 24, fd)
    # брови и морозное дыхание
    line(r, 43, 20, 49, 19, fd)
    for (x, y) in ((60, 20), (62, 17), (57, 17)):
        put(r, x, y, hx('#bfeaff'))

    # передние лапы
    box(31, 45, 41, 56, f)
    box(31, 45, 32, 55, fl)
    box(40, 45, 41, 55, fd)
    box(29, 55, 42, 63, fd)
    box(29, 55, 42, 56, fl)
    box(29, 62, 42, 63, fdd)
    # когти
    for x in (9, 14, 19, 29, 34, 39):
        put(r, x, 63, claw); put(r, x + 1, 63, claw)
    # блики
    for (x, y) in ((17, 33), (25, 40), (33, 30), (47, 30), (54, 22)):
        put(r, x, y, hx('#ffffff'))
    return r


